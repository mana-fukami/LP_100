#1列目の文字列の異なり（文字列の種類）を求めよ。
# 確認にはcut, sort, uniqコマンドを用いよ。

original_file=open("popular-names.txt","r")
lines=original_file.readlines()

#各行の1列目の情報を格納する
rows1=[]
for i in range(len(lines)):
    lines[i]=lines[i].replace("\t"," ")
    words=lines[i].split(" ")
    rows1.append(words[0])

#各行の1列目にあらわれる文字列の種類を求める
row1_kinds=[] #1列目の文字列の種類
for j in rows1:
    if j not in row1_kinds:
        row1_kinds.append(j)
row1_kinds.sort() #見やすいように辞書順に

for k in row1_kinds:
    print(k)

